"""Run the full ORCHID benchmark suite and write BENCHMARKS.md.

    python validation/run_all.py              # evaluate existing results only
    python validation/run_all.py --run        # re-run every benchmark, then evaluate
    python validation/run_all.py --run V24 V25  # re-run selected benchmarks

Re-running everything takes about an hour on 2 cores. bench_published_software
needs a NIST Sesame checkout (path in $SESAME_PATH, default /tmp/nist_sesame).
"""
import json
import os
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from criteria import CRITERIA, evaluate  # noqa: E402

TIMES = os.path.join(HERE, "results", "timings.json")


def run_scripts(ids):
    times = json.load(open(TIMES)) if os.path.exists(TIMES) else {}
    scripts = []
    for vid, _, _, script, _ in CRITERIA:
        if (not ids or vid in ids) and script not in scripts:
            scripts.append(script)
    for s in scripts:
        cmd = [sys.executable, os.path.join(HERE, s + ".py")]
        if s == "bench_published_software":
            cmd.append(os.environ.get("SESAME_PATH", "/tmp/nist_sesame"))
        print(f"--> {s}", flush=True)
        t0 = time.time()
        p = subprocess.run(cmd, cwd=HERE)
        times[s] = dict(seconds=round(time.time() - t0, 1), returncode=p.returncode,
                        date=time.strftime("%Y-%m-%d"))
        json.dump(times, open(TIMES, "w"), indent=1)


def write_report(rows):
    import orchid
    times = json.load(open(TIMES)) if os.path.exists(TIMES) else {}
    npass = sum(r["passed"] is True for r in rows)
    ncheck = sum(r["passed"] is not None for r in rows)
    L = ["# ORCHID benchmark report", "",
         f"ORCHID {orchid.__version__}. Generated by `python validation/run_all.py`; "
         "criteria in `validation/criteria.py`, figures in `validation/figures/`.", "",
         f"**{npass} / {ncheck} quantitative checks pass.** V27 records throughput only.", "",
         "| ID | Quantity | Reference | Result | Status | Runtime |",
         "|---|---|---|---|---|---|"]
    for r in rows:
        st = {True: "pass", False: "**FAIL**", None: "recorded"}[r["passed"]]
        t = times.get(r["script"], {}).get("seconds")
        L.append(f"| {r['id']} | {r['what']} | {r['reference']} | {r['value']} | {st} | "
                 f"{'' if t is None else f'{t:.0f} s'} |")
    perf = os.path.join(HERE, "results", "v27.json")
    if os.path.exists(perf):
        p = json.load(open(perf))
        m = p.pop("machine")
        L += ["", "## Throughput (V27)", "",
              f"{m['cpus']} CPU cores, Python {m['python']}, NumPy {m['numpy']}, Numba {m['numba']}.", "",
              "| Engine | Value |", "|---|---|"]
        for k, v in p.items():
            L.append(f"| `{k}` | {v:.3g} |")
    with open(os.path.join(ROOT, "BENCHMARKS.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    return npass, ncheck


def main(argv):
    if "--run" in argv:
        run_scripts([a for a in argv if a.startswith("V")])
    rows = evaluate()
    for r in rows:
        st = {True: "PASS", False: "FAIL", None: "INFO"}[r["passed"]]
        print(f"{r['id']:>4} {st}  {r['what']:<32} {r['value']}")
    npass, ncheck = write_report(rows)
    print(f"\n{npass}/{ncheck} checks pass -> BENCHMARKS.md")
    return 0 if npass == ncheck else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
